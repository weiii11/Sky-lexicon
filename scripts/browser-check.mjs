import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE, args: ['--disable-features=Translate'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
await context.route('**/*', route => {
  const url = new URL(route.request().url());
  return url.protocol.startsWith('http') && !['127.0.0.1', 'localhost'].includes(url.hostname) ? route.abort() : route.continue();
});
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const checks = [];
const vocabulary = JSON.parse(readFileSync(new URL('../src/vocabulary.json', import.meta.url), 'utf8'));
const output = new URL('../test-results/', import.meta.url);
mkdirSync(output, { recursive: true });
async function waitForGame() {
  await page.locator('#typing-input').waitFor();
  await page.waitForFunction(() => !document.querySelector('#typing-input').disabled, null, { timeout: 15000 });
}
async function submitCorrect() {
  const id = await page.locator('#typing-form').getAttribute('data-word-id');
  const value = vocabulary.words.find(word => word.id === id).text;
  await page.locator('#typing-input').fill(value);
}
try {
  await page.goto(process.env.PREVIEW_URL ?? 'http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.island').count(), 22);
  assert.equal(await page.locator('.chapter-link').count(), 22);
  assert.equal(await page.locator('#island-inspector h3').textContent(), '自然地理');
  await page.waitForFunction(() => [...document.querySelectorAll('.island-art')].slice(0, 3).every(img => img.complete && img.naturalWidth > 0));
  await page.screenshot({ path: fileURLToPath(new URL('map-desktop.png', output)), fullPage: true });
  checks.push('22 islands and chapters; images load; desktop map screenshot');
  await page.locator('.chapter-link[data-chapter="chapter-22"]').click();
  assert.equal(await page.locator('#island-inspector h3').textContent(), '时间日期');
  await page.locator('.chapter-link[data-chapter="chapter-05"]').click();
  await page.locator('#start-island').click();
  await waitForGame();
  assert.equal(await page.locator('canvas').count(), 1);
  assert.equal(await page.locator('#word-details').isVisible(), false);
  const firstId = await page.locator('#typing-form').getAttribute('data-word-id');
  const firstWord = vocabulary.words.find(word => word.id === firstId);
  await page.locator('#typing-input').fill(firstWord.text.slice(0, 2));
  assert.equal(await page.locator('#leaf-feedback .correct').count(), 2);
  assert.equal(await page.locator('#leaf-meaning').textContent(), firstWord.meaning);
  await page.locator('#details-toggle').click();
  assert.equal(await page.locator('#word-details').isVisible(), true);
  assert.equal(await page.locator('#typing-input').inputValue(), firstWord.text.slice(0, 2));
  await page.locator('#close-details').click();
  assert.equal(await page.locator('#word-details').isVisible(), false);
  await page.waitForFunction(() => document.querySelector('#typing-input') === document.activeElement);
  await page.locator('#typing-input').fill('');
  await page.screenshot({ path: fileURLToPath(new URL('game-desktop.png', output)), fullPage: true });
  checks.push('chapter selection and playable game canvas');
  checks.push('only word and meaning appear directly on the leaf, without a card or extra captions; annotations toggle without losing input or focus');
  await submitCorrect();
  assert.equal(await page.locator('#step-count').textContent(), '1');
  await page.waitForTimeout(600);
  await page.locator('#typing-input').fill('thisiswrong');
  await page.locator('#typing-input').press('Enter');
  await page.waitForTimeout(800);
  assert.equal(await page.locator('#lives .lost').count(), 1);
  assert.equal(await page.locator('#notebook-count').textContent(), '1');
  checks.push('correct typing advances; spelling error costs a life and saves the word');
  await page.locator('#pause-button').click();
  const remaining = await page.locator('#time-remaining').textContent();
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('#time-remaining').textContent(), remaining);
  await page.locator('#resume-game').click();
  await page.locator('#nav-notebook').click();
  assert.equal(await page.locator('.notebook-word').count(), 1);
  await page.screenshot({ path: fileURLToPath(new URL('notebook-desktop.png', output)), fullPage: true });
  await page.locator('#close-notebook').click();
  checks.push('pause freezes clock; notebook shows saved mistake');
  for (let i = 1; i < 12; i++) { await submitCorrect(); await page.waitForTimeout(450); }
  await page.locator('.result-dialog').waitFor({ state: 'visible' });
  assert.match(await page.locator('.result-dialog h2').textContent(), /到岸/);
  assert.equal(await page.locator('.round-word').count(), 13);
  await page.locator('.round-word summary').first().click();
  assert.equal(await page.locator('.round-word[open] .review-meaning').isVisible(), true);
  assert.ok((await page.locator('.round-word[open] .review-meaning').textContent()).length > 0);
  await page.screenshot({ path: fileURLToPath(new URL('result-desktop.png', output)), fullPage: true });
  await page.locator('#result-map').click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('sky-lexicon:v1')));
  assert.equal(saved.chapters['chapter-05'].completed, 1);
  checks.push('12 jumps complete a round; all 13 encountered correct/incorrect words have expandable review details');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('#notebook-count').textContent(), '1');
  await page.locator('#nav-notebook').click();
  await page.locator('#review-start').click(); await waitForGame();
  for (let i = 0; i < 2; i++) { await submitCorrect(); await page.waitForTimeout(450); }
  assert.equal(await page.locator('#mode-tag').textContent(), '中文回忆');
  const reviewId = await page.locator('#typing-form').getAttribute('data-word-id');
  const reviewWord = vocabulary.words.find(word => word.id === reviewId);
  assert.equal(await page.locator('#leaf-feedback .blank').count(), [...reviewWord.text].filter(c => /[\p{L}\p{N}]/u.test(c)).length);
  await page.locator('#typing-input').pressSequentially(reviewWord.text.slice(0, 1));
  assert.equal(await page.locator('#leaf-feedback .correct').count(), 1);
  await page.locator('#typing-input').press('Backspace');
  assert.equal(await page.locator('#leaf-feedback .correct').count(), 0);
  const oldEnglish = saved.words;
  assert.ok(Object.keys(oldEnglish).length > 0);
  await page.locator('#exit-game').click();
  checks.push('reload preserves notebook; two correct answers enable letter masks; typing fills letters and Backspace restores blanks');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#mobile-chapter-select').selectOption('chapter-22');
  assert.equal(await page.locator('#island-inspector h3').textContent(), '时间日期');
  await page.waitForTimeout(500);
  await page.screenshot({ path: fileURLToPath(new URL('map-mobile.png', output)), fullPage: true });
  await page.locator('#start-island').click(); await waitForGame();
  const leafBounds = await page.locator('#typing-form').boundingBox();
  const frameBounds = await page.locator('.garden-frame').boundingBox();
  assert.ok(leafBounds.x >= frameBounds.x && leafBounds.x + leafBounds.width <= frameBounds.x + frameBounds.width);
  await page.locator('#details-toggle').click();
  assert.equal(await page.locator('#word-details').isVisible(), true);
  await page.locator('#close-details').click();
  await page.screenshot({ path: fileURLToPath(new URL('game-mobile.png', output)), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.setViewportSize({ width: 1080, height: 760 });
  await submitCorrect();
  checks.push('mobile chapter selection; no horizontal page overflow; playable after resizing');
  await page.locator('#exit-game').click();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.locator('#start-island').click(); await waitForGame();
  for (let i = 0; i < 12; i++) await submitCorrect();
  await page.locator('.result-dialog').waitFor({ state: 'visible', timeout: 15000 });
  assert.match(await page.locator('.result-dialog h2').textContent(), /到岸/);
  await page.locator('#play-again').click(); await waitForGame();
  for (let i = 0; i < 3; i++) {
    await page.locator('#typing-input').fill('thisiswrong');
    await page.locator('#typing-form').evaluate(form => form.requestSubmit());
    await page.waitForTimeout(800);
  }
  await page.locator('.result-dialog').waitFor({ state: 'visible' });
  assert.match(await page.locator('.result-dialog h2').textContent(), /再出发/);
  await page.locator('#result-map').click();
  checks.push('normal animations handle rapid consecutive answers; three falls end the round; restart works');
  assert.deepEqual(errors, []);
  writeFileSync(new URL('browser-report.json', output), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: fileURLToPath(new URL('failure.png', output)), fullPage: true });
  console.error('PAGE ERRORS:', errors);
  throw error;
} finally { await browser.close(); }
